// Инъекция гранулярных IT-подролей и двуязычных алиасов в IT-категорию HH
// (id 11), сохраняя исходные категории снапшота.
export const PROFESSIONAL_ROLE_CATEGORIES: ProfessionalRoleCategory[] =
  RAW_PROFESSIONAL_ROLE_CATEGORIES.map((category) => {
    const roles = category.roles.map((role) => {
      const patch = IT_ALIAS_PATCH[role.name];
      return patch
        ? { ...role, aliases: [...(role.aliases ?? []), ...patch] }
        : role;
    });
    return category.id === '11'
      ? { ...category, roles: [...IT_EXTRA_ROLES, ...roles] }
      : { ...category, roles };
  });

export const PROFESSIONAL_ROLE_OPTIONS = PROFESSIONAL_ROLE_CATEGORIES.flatMap(
  (category) =>
    category.roles.map((role) => ({
      ...role,
      categoryId: category.id,
      categoryName: category.name,
    }))
);
