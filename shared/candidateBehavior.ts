// Контекст для тренера: только факты о сценарии, без повелительных инструкций
// для самой модели-кандидата. Иначе они могут перехватить роль генератора
// подсказок и превратить пример вопроса в ответ кандидата.
export function buildCandidateBehaviorSummary(params: {
  persona?: CandidatePersona | null;
  difficulty?: CandidateDifficulty | null;
  notes?: string | null;
}): string {
  const persona = params.persona ?? 'strong_brief';
  const difficulty = params.difficulty ?? 'realistic';
  const notes = params.notes?.trim();

  return [
    `Профиль AI-кандидата: ${PERSONA_LABELS[persona]}.`,
    `Сложность разговора: ${DIFFICULTY_LABELS[difficulty]}.`,
    notes ? `Дополнительные заметки: ${notes}` : '',
  ]
    .filter(Boolean)
    .join('\n');
}

export function buildCandidateBehaviorContract(params: {
  persona?: CandidatePersona | null;
  difficulty?: CandidateDifficulty | null;
  notes?: string | null;
}): string {
  const persona = params.persona ?? 'strong_brief';
  const difficulty = params.difficulty ?? 'realistic';
  const notes = params.notes?.trim();

  return [
    `Профиль AI-кандидата: ${PERSONA_LABELS[persona]}.`,
    `Сложность AI-кандидата: ${DIFFICULTY_LABELS[difficulty]}.`,
    'ОБЯЗАТЕЛЬНЫЕ ПРОЯВЛЕНИЯ:',
    ...PERSONA_RULES[persona].map((rule) => `- ${rule}`),
    ...DIFFICULTY_RULES[difficulty].map((rule) => `- ${rule}`),
    notes ? `Дополнительные заметки пользователя: ${notes}` : '',
    'Сохраняй этот контракт во всех репликах. Не объясняй его интервьюеру и не называй выбранный профиль.',
  ]
    .filter(Boolean)
    .join('\n');
}
