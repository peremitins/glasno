import { describe, expect, it } from 'vitest';
import {
  isNextQuestionTransitionReply,
  isNextQuestionVoiceCommand,
} from './interviewVoiceCommand';

describe('interview voice commands', () => {
  it.each([
    'следующий вопрос',
    'Следующий вопрос.',
    'давай следующий вопрос',
    'перейдем к следующему вопросу',
    'перейдём к следующему вопросу',
    'давай перейдем к следующему вопросу',
    'давайте перейдём к следующему вопросу',
    'перейди к следующему вопросу',
    'переходи к следующему вопросу',
    'переходим к следующему вопросу',
    'можем перейти к следующему вопросу',
    'переключи на следующий вопрос',
    'переключаемся на следующий вопрос',
    'хочу перейти к следующему вопросу',
    'к следующему вопросу',
    'давай другой вопрос',
    'можно другой вопрос',
    'другой вопрос пожалуйста',
    'перейдем к другому вопросу',
    'переключи на другой вопрос',
    'поменяй вопрос',
    'смени вопрос',
  ])('accepts "%s"', (command) => {
    expect(isNextQuestionVoiceCommand(command)).toBe(true);
  });

  it.each([
    'дальше',
    'давай дальше',
    'продолжай дальше',
    'почему ты не переходишь к вопросу',
    'на какая команда должна быть',
    'следующий пример по TypeScript',
    'можем обсудить следующий вопрос в конце ответа',
  ])('rejects "%s"', (command) => {
    expect(isNextQuestionVoiceCommand(command)).toBe(false);
  });

  it.each([
    'Понял, переходим к следующему вопросу.',
    'Поняла, переходим к следующему вопросу.',
    'Хорошо, давайте перейдем к следующему вопросу.',
    'Окей, переключаюсь на другой вопрос.',
    'Отлично, идем дальше.',
    'Хорошо, молчу, ждём следующий вопрос.',
    'Понял, жду следующий вопрос.',
    'Хорошо, жду следующего вопроса.',
    'Договорились, перехожу к следующему вопросу.',
    'Принято, молчу, ждем следующий вопрос.',
  ])('accepts assistant transition reply "%s"', (reply) => {
    expect(isNextQuestionTransitionReply(reply)).toBe(true);
  });

  it.each([
    'Можем перейти к следующему вопросу?',
    'Хотите перейти к другому вопросу?',
    'Если готовы, перейдем к следующему вопросу.',
    'В следующем вопросе мы обсудим метрики.',
  ])('rejects assistant non-transition reply "%s"', (reply) => {
    expect(isNextQuestionTransitionReply(reply)).toBe(false);
  });
});
